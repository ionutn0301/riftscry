import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const root = '/tmp/agent-browser/atlas-proof';
await mkdir(root, { recursive: true });
const browser = await chromium.launch({ args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, recordVideo: { dir: root, size: { width: 1280, height: 900 } } });
const page = await context.newPage();
await page.goto('http://localhost:4321');
await page.waitForFunction(() => window.__riftAtlas?.ready === true);
await page.waitForFunction(() => window.__riftAtlas.progress === 1);
const samples = [];
async function sample(label) { samples.push(await page.evaluate(label => ({ label, ...window.__riftAtlas }), label)); }
await sample('arrival');
await page.screenshot({ path: `${root}/entry-start.png` });
await page.getByRole('button', { name: 'Explore the Atlas', exact: true }).click();
await page.waitForTimeout(450);
await page.screenshot({ path: `${root}/entry-midpoint.png` });
await page.waitForFunction(() => window.__riftAtlas.state.view === 'champions' && window.__riftAtlas.progress === 1);
await page.screenshot({ path: `${root}/entry-end.png` });
await sample('entry');
await page.getByRole('button', { name: 'Azir 4 recorded changes', exact: true }).click();
await page.waitForFunction(() => window.__riftAtlas.state.championId === 'Azir' && window.__riftAtlas.state.view === 'champion' && window.__riftAtlas.progress === 1);
await page.waitForTimeout(3000);
await sample('champion');
await page.getByRole('button', { name: 'Patch History', exact: true }).click();
await page.waitForFunction(() => window.__riftAtlas.state.view === 'history' && window.__riftAtlas.progress === 1);
await page.waitForTimeout(3000);
await page.getByRole('button', { name: 'Compare changes', exact: true }).click();
await page.waitForFunction(() => window.__riftAtlas.state.view === 'compare' && window.__riftAtlas.progress === 1);
await page.waitForTimeout(2000);
await sample('compare');
const first = page.getByRole('slider', { name: /First endpoint/ });
await first.focus(); await page.keyboard.press('Home');
await page.waitForFunction(() => window.__riftAtlas.state.comparisonFrom === '26.1' && window.__riftAtlas.progress === 1);
await page.waitForTimeout(3000);
await sample('expanded interval');
await page.getByRole('button', { name: 'Close comparison', exact: true }).click();
await page.waitForFunction(() => window.__riftAtlas.state.view === 'history' && window.__riftAtlas.progress === 1);
await page.waitForTimeout(2500);
await sample('reverse');
const video = page.video(); await context.close(); await video.saveAs(`${root}/moving-slice.webm`);
await writeFile(`${root}/slice-evidence.json`, JSON.stringify(samples, null, 2));
await browser.close();
console.log(JSON.stringify({ video: `${root}/moving-slice.webm`, rendererIds: [...new Set(samples.map(s => s.renderer))], states: samples.map(s => ({ label: s.label, camera: s.camera, mode: s.mode })) }, null, 2));
